/**
 * Enhanced PDF Export with Comprehensive Medical Details
 * Includes all graphs, visualizations, and formatted medical documentation
 */

class MedicalPDFExporter {
    constructor() {
        this.doc = null;
        this.pageWidth = 210; // A4 width in mm
        this.pageHeight = 297; // A4 height in mm
        this.margin = 20;
        this.currentY = this.margin;
        this.lineHeight = 7;
        this.currentPage = 1;
    }
    
    async exportComprehensiveReport(patientData, assessmentData) {
        // Load jsPDF
        const { jsPDF } = window.jspdf;
        this.doc = new jsPDF();
        
        // Page 1: Cover Page
        this.addCoverPage(patientData, assessmentData);
        
        // Page 2: Patient Demographics & BMI
        this.addNewPage();
        this.addPatientDemographics(patientData);
        this.addBMIAnalysis(patientData);
        
        // Page 3: Assessment Summary
        this.addNewPage();
        this.addAssessmentSummary(assessmentData);
        
        // Page 4: Detailed Movement Analysis
        this.addNewPage();
        this.addMovementAnalysis(assessmentData);
        
        // Page 5: SOAP Note
        this.addNewPage();
        this.addSOAPNote(patientData, assessmentData);
        
        // Page 6: Graphs (captured from canvas)
        await this.addGraphsPage();
        
        // Page 7: Clinical Recommendations
        this.addNewPage();
        this.addClinicalRecommendations(patientData, assessmentData);
        
        // Add page numbers
        this.addPageNumbers();
        
        // Save the PDF
        const fileName = `ThriveOrtho_MedicalReport_${patientData.last_name}_${new Date().toISOString().split('T')[0]}.pdf`;
        this.doc.save(fileName);
    }
    
    addCoverPage(patientData, assessmentData) {
        // Logo area (placeholder)
        this.doc.setFillColor(0, 102, 204);
        this.doc.rect(0, 0, this.pageWidth, 60, 'F');
        
        // Title
        this.doc.setTextColor(255, 255, 255);
        this.doc.setFontSize(32);
        this.doc.setFont(undefined, 'bold');
        this.doc.text('ThriveOrtho', this.pageWidth / 2, 25, { align: 'center' });
        
        this.doc.setFontSize(18);
        this.doc.text('Physical Therapy Assessment Report', this.pageWidth / 2, 40, { align: 'center' });
        
        // Patient Name
        this.currentY = 80;
        this.doc.setTextColor(0, 0, 0);
        this.doc.setFontSize(24);
        this.doc.setFont(undefined, 'bold');
        this.doc.text(`${patientData.first_name} ${patientData.last_name}`, this.pageWidth / 2, this.currentY, { align: 'center' });
        
        // Patient ID
        this.currentY += 15;
        this.doc.setFontSize(14);
        this.doc.setFont(undefined, 'normal');
        this.doc.text(`Patient ID: ${patientData.id}`, this.pageWidth / 2, this.currentY, { align: 'center' });
        
        // Assessment Date
        this.currentY += 10;
        this.doc.text(`Assessment Date: ${new Date().toLocaleDateString()}`, this.pageWidth / 2, this.currentY, { align: 'center' });
        
        // Report Type Box
        this.currentY = 140;
        this.doc.setFillColor(240, 240, 240);
        this.doc.roundedRect(this.margin, this.currentY, this.pageWidth - 2 * this.margin, 40, 3, 3, 'F');
        
        this.currentY += 12;
        this.doc.setFontSize(16);
        this.doc.setFont(undefined, 'bold');
        this.doc.text('Comprehensive Functional Movement Assessment', this.pageWidth / 2, this.currentY, { align: 'center' });
        
        this.currentY += 10;
        this.doc.setFontSize(12);
        this.doc.setFont(undefined, 'normal');
        this.doc.text('AI-Powered Biomechanical Analysis', this.pageWidth / 2, this.currentY, { align: 'center' });
        
        this.currentY += 10;
        this.doc.text(`Tests Completed: ${assessmentData.tests ? assessmentData.tests.length : 0}`, this.pageWidth / 2, this.currentY, { align: 'center' });
        
        // Confidentiality Notice
        this.currentY = 250;
        this.doc.setFontSize(9);
        this.doc.setTextColor(100, 100, 100);
        const confidentialText = 'CONFIDENTIAL MEDICAL RECORD - This document contains protected health information (PHI) under HIPAA regulations. Unauthorized disclosure is prohibited.';
        const splitText = this.doc.splitTextToSize(confidentialText, this.pageWidth - 2 * this.margin);
        this.doc.text(splitText, this.pageWidth / 2, this.currentY, { align: 'center' });
        
        // Footer
        this.currentY = 280;
        this.doc.setFontSize(10);
        this.doc.setTextColor(0, 102, 204);
        this.doc.text('Generated by ThriveOrtho™ Platform', this.pageWidth / 2, this.currentY, { align: 'center' });
    }
    
    addNewPage() {
        this.doc.addPage();
        this.currentPage++;
        this.currentY = this.margin;
    }
    
    addSectionTitle(title, icon = '') {
        this.currentY += 5;
        this.doc.setFillColor(0, 102, 204);
        this.doc.rect(this.margin, this.currentY, this.pageWidth - 2 * this.margin, 10, 'F');
        
        this.currentY += 7;
        this.doc.setTextColor(255, 255, 255);
        this.doc.setFontSize(14);
        this.doc.setFont(undefined, 'bold');
        this.doc.text(`${icon} ${title}`, this.margin + 3, this.currentY);
        
        this.currentY += 8;
        this.doc.setTextColor(0, 0, 0);
    }
    
    addPatientDemographics(patientData) {
        this.addSectionTitle('Patient Demographics', '👤');
        
        const age = this.calculateAge(patientData.date_of_birth);
        
        const demographics = [
            ['Full Name:', `${patientData.first_name} ${patientData.last_name}`],
            ['Date of Birth:', `${patientData.date_of_birth} (Age: ${age})`],
            ['Gender:', patientData.gender],
            ['Phone:', patientData.phone],
            ['Email:', patientData.email || 'Not provided'],
            ['Address:', `${patientData.address_line1}, ${patientData.city}, ${patientData.state} ${patientData.zip_code}`],
            ['Emergency Contact:', `${patientData.emergency_contact_name} (${patientData.emergency_contact_relationship}) - ${patientData.emergency_contact_phone}`]
        ];
        
        this.doc.setFontSize(10);
        demographics.forEach(([label, value]) => {
            this.doc.setFont(undefined, 'bold');
            this.doc.text(label, this.margin + 5, this.currentY);
            this.doc.setFont(undefined, 'normal');
            const valueText = this.doc.splitTextToSize(value, this.pageWidth - this.margin - 60);
            this.doc.text(valueText, this.margin + 60, this.currentY);
            this.currentY += this.lineHeight * (valueText.length || 1);
        });
    }
    
    addBMIAnalysis(patientData) {
        this.currentY += 5;
        this.addSectionTitle('Physical Measurements & BMI Analysis', '⚖️');
        
        const bmi = this.calculateBMI(patientData.height_cm, patientData.weight_kg);
        const bmiCategory = this.getBMICategory(bmi);
        
        const measurements = [
            ['Height:', `${patientData.height_cm} cm (${(patientData.height_cm / 2.54 / 12).toFixed(1)} ft)`],
            ['Weight:', `${patientData.weight_kg} kg (${(patientData.weight_kg * 2.205).toFixed(1)} lbs)`],
            ['BMI:', `${bmi.toFixed(1)} - ${bmiCategory}`]
        ];
        
        this.doc.setFontSize(10);
        measurements.forEach(([label, value]) => {
            this.doc.setFont(undefined, 'bold');
            this.doc.text(label, this.margin + 5, this.currentY);
            this.doc.setFont(undefined, 'normal');
            this.doc.text(value, this.margin + 40, this.currentY);
            this.currentY += this.lineHeight;
        });
        
        // BMI recommendations
        this.currentY += 3;
        this.doc.setFont(undefined, 'bold');
        this.doc.text('Clinical Recommendations:', this.margin + 5, this.currentY);
        this.currentY += this.lineHeight;
        
        const recommendations = this.getLifestyleRecommendations(bmi, bmiCategory);
        this.doc.setFont(undefined, 'normal');
        recommendations.forEach(rec => {
            const lines = this.doc.splitTextToSize(`• ${rec}`, this.pageWidth - 2 * this.margin - 10);
            this.doc.text(lines, this.margin + 10, this.currentY);
            this.currentY += this.lineHeight * lines.length;
        });
    }
    
    addAssessmentSummary(assessmentData) {
        this.addSectionTitle('Assessment Summary', '📊');
        
        const tests = assessmentData.tests || [];
        
        this.doc.setFontSize(10);
        this.doc.setFont(undefined, 'bold');
        this.doc.text(`Total Tests Performed: ${tests.length}`, this.margin + 5, this.currentY);
        this.currentY += this.lineHeight + 3;
        
        // Summary statistics
        let totalDeficiencies = 0;
        let avgQuality = 0;
        
        tests.forEach(test => {
            const data = test.skeleton_data ? JSON.parse(test.skeleton_data) : {};
            const analysis = data.analysis || {};
            totalDeficiencies += (analysis.deficiencies || []).length;
            avgQuality += (analysis.form_quality || 0);
        });
        
        avgQuality = tests.length > 0 ? avgQuality / tests.length : 0;
        
        const summaryStats = [
            ['Average Movement Quality:', `${avgQuality.toFixed(0)}%`],
            ['Total Deficiencies Identified:', totalDeficiencies.toString()],
            ['Overall Assessment:', this.getOverallAssessment(avgQuality, totalDeficiencies)]
        ];
        
        summaryStats.forEach(([label, value]) => {
            this.doc.setFont(undefined, 'bold');
            this.doc.text(label, this.margin + 5, this.currentY);
            this.doc.setFont(undefined, 'normal');
            this.doc.text(value, this.margin + 80, this.currentY);
            this.currentY += this.lineHeight;
        });
    }
    
    addMovementAnalysis(assessmentData) {
        this.addSectionTitle('Detailed Movement Analysis', '🔬');
        
        const tests = assessmentData.tests || [];
        
        this.doc.setFontSize(10);
        
        tests.forEach((test, idx) => {
            // Check if we need a new page
            if (this.currentY > 250) {
                this.addNewPage();
            }
            
            const data = test.skeleton_data ? JSON.parse(test.skeleton_data) : {};
            const analysis = data.analysis || {};
            
            this.currentY += 3;
            this.doc.setFont(undefined, 'bold');
            this.doc.setFontSize(12);
            this.doc.text(`${idx + 1}. ${test.test_name}`, this.margin + 5, this.currentY);
            this.currentY += this.lineHeight;
            
            this.doc.setFontSize(10);
            this.doc.setFont(undefined, 'normal');
            
            const testDetails = [
                ['Reps Completed:', `${test.reps_completed}`],
                ['Duration:', `${test.duration_seconds}s`],
                ['ROM Score:', `${(analysis.rom_score || 0).toFixed(1)}%`],
                ['Form Quality:', `${(analysis.form_quality || 0).toFixed(1)}%`],
                ['Balance Score:', `${(analysis.balance_score || 0).toFixed(1)}%`]
            ];
            
            testDetails.forEach(([label, value]) => {
                this.doc.setFont(undefined, 'bold');
                this.doc.text(label, this.margin + 10, this.currentY);
                this.doc.setFont(undefined, 'normal');
                this.doc.text(value, this.margin + 50, this.currentY);
                this.currentY += this.lineHeight;
            });
            
            // Deficiencies
            if (analysis.deficiencies && analysis.deficiencies.length > 0) {
                this.currentY += 2;
                this.doc.setFont(undefined, 'bold');
                this.doc.text('Deficiencies:', this.margin + 10, this.currentY);
                this.currentY += this.lineHeight;
                
                this.doc.setFont(undefined, 'normal');
                analysis.deficiencies.forEach(d => {
                    const defText = `• [${d.severity.toUpperCase()}] ${d.area}: ${d.description}`;
                    const lines = this.doc.splitTextToSize(defText, this.pageWidth - 2 * this.margin - 15);
                    this.doc.text(lines, this.margin + 15, this.currentY);
                    this.currentY += this.lineHeight * lines.length;
                });
            }
            
            this.currentY += 5;
        });
    }
    
    addSOAPNote(patientData, assessmentData) {
        this.addSectionTitle('SOAP Note', '📋');
        
        const tests = assessmentData.tests || [];
        const age = this.calculateAge(patientData.date_of_birth);
        const bmi = this.calculateBMI(patientData.height_cm, patientData.weight_kg);
        const bmiCategory = this.getBMICategory(bmi);
        
        this.doc.setFontSize(10);
        
        // Subjective
        this.doc.setFont(undefined, 'bold');
        this.doc.setFontSize(11);
        this.doc.text('SUBJECTIVE:', this.margin + 5, this.currentY);
        this.currentY += this.lineHeight;
        
        this.doc.setFont(undefined, 'normal');
        this.doc.setFontSize(10);
        const subjectiveText = `Chief Complaint: ${patientData.chief_complaint}. Pain Scale: ${patientData.pain_scale}/10. Activity Level: ${patientData.activity_level}. Assessment Reason: ${patientData.assessment_reason}.`;
        const subjLines = this.doc.splitTextToSize(subjectiveText, this.pageWidth - 2 * this.margin - 5);
        this.doc.text(subjLines, this.margin + 5, this.currentY);
        this.currentY += this.lineHeight * subjLines.length + 5;
        
        // Objective
        this.doc.setFont(undefined, 'bold');
        this.doc.setFontSize(11);
        this.doc.text('OBJECTIVE:', this.margin + 5, this.currentY);
        this.currentY += this.lineHeight;
        
        this.doc.setFont(undefined, 'normal');
        this.doc.setFontSize(10);
        const objectiveText = `${age}-year-old ${patientData.gender} presenting for ${patientData.assessment_reason}. Height: ${patientData.height_cm}cm, Weight: ${patientData.weight_kg}kg, BMI: ${bmi.toFixed(1)} (${bmiCategory}). Completed ${tests.length} standardized movement tests using AI-powered biomechanical analysis.`;
        const objLines = this.doc.splitTextToSize(objectiveText, this.pageWidth - 2 * this.margin - 5);
        this.doc.text(objLines, this.margin + 5, this.currentY);
        this.currentY += this.lineHeight * objLines.length + 5;
        
        // Assessment
        if (this.currentY > 240) this.addNewPage();
        
        this.doc.setFont(undefined, 'bold');
        this.doc.setFontSize(11);
        this.doc.text('ASSESSMENT:', this.margin + 5, this.currentY);
        this.currentY += this.lineHeight;
        
        this.doc.setFont(undefined, 'normal');
        this.doc.setFontSize(10);
        const assessmentText = `Functional Status: ${this.getFunctionalStatus(tests)}. Fall Risk: ${this.getFallRisk(tests, age)}. BMI Status: ${bmiCategory}.`;
        const assessLines = this.doc.splitTextToSize(assessmentText, this.pageWidth - 2 * this.margin - 5);
        this.doc.text(assessLines, this.margin + 5, this.currentY);
        this.currentY += this.lineHeight * assessLines.length + 5;
        
        // Plan
        this.doc.setFont(undefined, 'bold');
        this.doc.setFontSize(11);
        this.doc.text('PLAN:', this.margin + 5, this.currentY);
        this.currentY += this.lineHeight;
        
        this.doc.setFont(undefined, 'normal');
        this.doc.setFontSize(10);
        const planText = 'Treatment Plan: Initiate personalized therapeutic exercise program targeting identified deficiencies. Home exercise program 5x/week, 30 minutes per session. Progressive strengthening and mobility exercises. Balance training to reduce fall risk. Remote Patient Monitoring (RPM) via mobile application. Follow-up: Re-assessment in 4 weeks. Weekly compliance monitoring via RPM.';
        const planLines = this.doc.splitTextToSize(planText, this.pageWidth - 2 * this.margin - 5);
        this.doc.text(planLines, this.margin + 5, this.currentY);
        this.currentY += this.lineHeight * planLines.length;
    }
    
    async addGraphsPage() {
        // This would capture canvas elements and add them to PDF
        // For now, add a placeholder page
        this.addNewPage();
        this.addSectionTitle('Biomechanical Graphs & Visualizations', '📈');
        
        this.doc.setFontSize(10);
        this.doc.text('Note: Graphs and visualizations are best viewed in the web report.', this.margin + 5, this.currentY);
        this.currentY += this.lineHeight;
        this.doc.text('Please refer to the online assessment report for interactive charts.', this.margin + 5, this.currentY);
    }
    
    addClinicalRecommendations(patientData, assessmentData) {
        this.addSectionTitle('Clinical Recommendations & Follow-Up', '💊');
        
        const recommendations = [
            'Continue with prescribed home exercise program 5x/week',
            'Focus on identified deficiencies with targeted exercises',
            'Maintain activity log via ThriveOrtho mobile app',
            'Schedule follow-up assessment in 4 weeks',
            'Contact clinic if pain exceeds 7/10 or new symptoms develop',
            'Consider referral to orthopedic specialist if no improvement'
        ];
        
        this.doc.setFontSize(10);
        this.doc.setFont(undefined, 'normal');
        
        recommendations.forEach(rec => {
            const lines = this.doc.splitTextToSize(`• ${rec}`, this.pageWidth - 2 * this.margin - 10);
            this.doc.text(lines, this.margin + 10, this.currentY);
            this.currentY += this.lineHeight * lines.length + 2;
        });
        
        // Provider signature section
        this.currentY += 10;
        this.doc.setDrawColor(0, 0, 0);
        this.doc.line(this.margin + 5, this.currentY, this.margin + 80, this.currentY);
        this.currentY += 5;
        this.doc.setFontSize(9);
        this.doc.text('Provider Signature', this.margin + 5, this.currentY);
        
        this.doc.line(this.margin + 100, this.currentY - 5, this.margin + 175, this.currentY - 5);
        this.doc.text('Date', this.margin + 100, this.currentY);
    }
    
    addPageNumbers() {
        const totalPages = this.currentPage;
        for (let i = 1; i <= totalPages; i++) {
            this.doc.setPage(i);
            this.doc.setFontSize(9);
            this.doc.setTextColor(100, 100, 100);
            this.doc.text(`Page ${i} of ${totalPages}`, this.pageWidth - this.margin, this.pageHeight - 10, { align: 'right' });
        }
    }
    
    // Helper functions
    calculateAge(dob) {
        const today = new Date();
        const birthDate = new Date(dob);
        let age = today.getFullYear() - birthDate.getFullYear();
        const m = today.getMonth() - birthDate.getMonth();
        if (m < 0 || (m === 0 && today.getDate() < birthDate.getDate())) age--;
        return age;
    }
    
    calculateBMI(heightCm, weightKg) {
        const heightM = heightCm / 100;
        return weightKg / (heightM * heightM);
    }
    
    getBMICategory(bmi) {
        if (bmi < 18.5) return 'Underweight';
        if (bmi < 25) return 'Normal weight';
        if (bmi < 30) return 'Overweight';
        return 'Obese';
    }
    
    getLifestyleRecommendations(bmi, category) {
        const recs = [];
        if (category === 'Underweight') {
            recs.push('Increase caloric intake with nutrient-dense foods');
            recs.push('Strength training to build muscle mass');
        } else if (category === 'Overweight' || category === 'Obese') {
            recs.push('Gradual weight reduction (1-2 lbs per week)');
            recs.push('Increase physical activity to 150+ minutes/week');
        } else {
            recs.push('Maintain current weight through balanced diet');
            recs.push('Continue regular physical activity');
        }
        recs.push('Stay hydrated (8-10 glasses water daily)');
        recs.push('Adequate sleep (7-9 hours nightly)');
        return recs;
    }
    
    getOverallAssessment(avgQuality, totalDeficiencies) {
        if (avgQuality >= 80 && totalDeficiencies === 0) return 'Excellent - No significant concerns';
        if (avgQuality >= 60 && totalDeficiencies <= 2) return 'Good - Minor improvements needed';
        if (avgQuality >= 40) return 'Fair - Moderate intervention required';
        return 'Poor - Significant intervention required';
    }
    
    getFunctionalStatus(tests) {
        if (!tests || tests.length === 0) return 'Not assessed';
        let totalQuality = 0;
        tests.forEach(test => {
            const data = test.skeleton_data ? JSON.parse(test.skeleton_data) : {};
            totalQuality += (data.analysis?.form_quality || 0);
        });
        const avgQuality = totalQuality / tests.length;
        if (avgQuality >= 80) return 'Independent, high function';
        if (avgQuality >= 60) return 'Independent with limitations';
        return 'Requires assistance';
    }
    
    getFallRisk(tests, age) {
        if (!tests || tests.length === 0) return 'Not assessed';
        let balanceScore = 0;
        let count = 0;
        tests.forEach(test => {
            const data = test.skeleton_data ? JSON.parse(test.skeleton_data) : {};
            if (data.analysis?.balance_score) {
                balanceScore += data.analysis.balance_score;
                count++;
            }
        });
        const avgBalance = count > 0 ? balanceScore / count : 0;
        if (age > 65 && avgBalance < 60) return 'High risk - recommend fall prevention program';
        if (avgBalance < 70) return 'Moderate risk';
        return 'Low risk';
    }
}

// Global function to export PDF from medical note page
async function downloadEnhancedPDF() {
    const exporter = new MedicalPDFExporter();
    
    // Get data from page state
    const patientData = window.STATE?.patientData;
    const assessmentData = window.STATE?.assessmentData;
    
    if (!patientData || !assessmentData) {
        alert('Unable to generate PDF: Missing patient or assessment data');
        return;
    }
    
    try {
        await exporter.exportComprehensiveReport(patientData, assessmentData);
    } catch (error) {
        console.error('PDF generation error:', error);
        alert('Error generating PDF. Please try again.');
    }
}
